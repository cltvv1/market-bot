import assert from 'node:assert/strict';
import PDFDocument from 'pdfkit';

// Runs inside the repository's existing isolated, headless CI smoke harness.
export async function verifyAdminWorkspace(page, baseUrl) {
    const checks = [];
    const confirm = async (name) => {
        await page.getByRole('button', { name, exact: true }).click();
        await page.getByRole('dialog').getByRole('button', { name, exact: true }).click();
        await page.getByRole('dialog').waitFor({ state: 'hidden' });
        await page.waitForLoadState('networkidle');
    };
    assert.match(page.url(), /\/admin\/requests\/service/);
    await page.reload({ waitUntil: 'networkidle' });
    await page.getByRole('heading', { name: 'Сервисные заявки', exact: true }).waitFor();
    checks.push('nested login and queue reload');
    await page.getByRole('combobox', { name: 'Приоритет', exact: true }).selectOption('high');
    await page.reload({ waitUntil: 'networkidle' });
    assert.match(page.url(), /priority=high/);
    assert.equal(await page.getByRole('combobox', { name: 'Приоритет', exact: true }).inputValue(), 'high');
    checks.push('server filter URL survives reload');
    await page.getByRole('region', { name: 'Фильтры заявок' }).getByRole('button', { name: 'Сбросить фильтры' }).click();
    await page.getByRole('button', { name: 'Создать заявку', exact: true }).click();
    await page.getByRole('combobox', { name: 'Услуга', exact: true }).selectOption('firmware_update');
    await page.getByRole('textbox', { name: 'Контактное лицо', exact: true }).fill('CI synthetic customer');
    await page.getByRole('textbox', { name: 'Телефон', exact: true }).fill('+70000000000');
    await page.getByRole('textbox', { name: 'Описание', exact: true }).fill('Synthetic browser regression. No external delivery.');
    await page.getByRole('dialog').getByRole('button', { name: 'Создать заявку', exact: true }).click();
    await page.waitForURL(/\/admin\/requests\/service\/\d+/);
    await page.waitForLoadState('networkidle');
    const detailUrl = page.url();
    checks.push('manual create redirects to real detail');
    await page.getByRole('button', { name: 'Приоритет и комментарий', exact: true }).click();
    await page.getByRole('combobox', { name: 'Приоритет', exact: true }).selectOption('urgent');
    await page.getByRole('textbox', { name: 'Внутренний комментарий', exact: true }).fill('CI private comment');
    await page.getByRole('dialog').getByRole('button', { name: 'Приоритет и комментарий', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.getByText('CI private comment', { exact: true }).waitFor();
    checks.push('operator fields persisted');
    await page.getByText('Другие действия', { exact: true }).click();
    await confirm('Отправить на рассмотрение');
    checks.push('canonical submit transition');
    await page.getByRole('tab', { name: 'Переписка', exact: true }).click();
    await page.getByRole('textbox', { name: 'Сообщение клиенту' }).fill('CI customer-visible message');
    await page.getByRole('button', { name: 'Отправить', exact: true }).click();
    await page.getByText('CI customer-visible message', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Внутренняя заметка', exact: true }).click();
    await page.getByRole('textbox', { name: 'Заметка для сотрудников' }).fill('CI internal-only note');
    await page.getByRole('button', { name: 'Добавить заметку', exact: true }).click();
    await page.getByText('CI internal-only note', { exact: true }).waitFor();
    await page.reload({ waitUntil: 'networkidle' });
    assert.match(page.url(), /tab=messages/);
    checks.push('customer/internal messages and tab URL reload');
    await page.getByRole('tab', { name: 'Заявка', exact: true }).click();
    await page.getByText('Другие действия', { exact: true }).click();
    await confirm('Подготовить счёт');
    await page.getByRole('button', { name: 'Загрузить счёт', exact: true }).click();
    const document = new PDFDocument();
    const chunks = [];
    const complete = new Promise((resolve, reject) => { document.on('data', value => chunks.push(value)); document.on('end', resolve); document.on('error', reject); });
    document.text('CI SYNTHETIC INVOICE. NOT FOR PAYMENT.');
    document.end();
    await complete;
    const invoice = { name: 'ci-invoice.pdf', mimeType: 'application/pdf', buffer: Buffer.concat(chunks) };
    await page.getByLabel('Счёт в PDF', { exact: true }).setInputFiles(invoice);
    await page.getByRole('dialog').getByRole('button', { name: 'Загрузить счёт', exact: true }).click();
    await page.getByRole('heading', { name: 'Проверка оплаты', exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Подтвердить оплату', exact: true }).isDisabled(), true);
    checks.push('PDF upload changes stage; no proof cannot confirm payment');
    await page.getByRole('button', { name: 'Заменить счёт', exact: true }).click();
    await page.getByLabel('Счёт в PDF', { exact: true }).setInputFiles({ ...invoice, name: 'ci-invoice-replacement.pdf' });
    await page.getByRole('dialog').getByRole('button', { name: 'Заменить счёт', exact: true }).click();
    await page.getByText('ci-invoice-replacement.pdf', { exact: true }).waitFor();
    checks.push('invoice replacement');
    await confirm('Отменить заявку');
    await page.getByRole('heading', { name: 'Отменена', exact: true }).waitFor();
    await page.getByRole('tab', { name: 'Переписка', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: 'Отправить', exact: true }).isDisabled(), true);
    checks.push('cancel and terminal message guard');
    await page.getByRole('tab', { name: 'История', exact: true }).click();
    await page.reload({ waitUntil: 'networkidle' });
    await page.getByRole('heading', { name: 'История заявки', exact: true }).waitFor();
    await page.goBack({ waitUntil: 'networkidle' });
    assert.match(page.url(), /tab=messages/);
    await page.goForward({ waitUntil: 'networkidle' });
    assert.match(page.url(), /tab=history/);
    checks.push('detail history Back/Forward');
    for (const route of ['/work', '/requests/registrations', '/requests/tickets', '/customers/access', '/customers/organizations', '/customers/equipment', '/integrations/signals', '/integrations/runs', '/settings/staff', '/settings/notifications', '/settings/audit']) {
        const response = await page.goto(`${baseUrl}/admin${route}`, { waitUntil: 'networkidle' });
        assert.equal(response.status(), 200);
        await page.getByRole('main').waitFor();
        assert.ok((await page.getByRole('main').innerText()).trim(), route);
        checks.push(`built route ${route}`);
    }
    await page.goto(detailUrl, { waitUntil: 'networkidle' });
    for (const [width, height] of [[1440,1000], [1280,900], [768,1024], [390,844]]) {
        await page.setViewportSize({ width, height });
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `overflow ${width}`);
        checks.push(`viewport ${width}x${height}`);
    }
    await page.getByRole('button', { name: 'Открыть навигацию' }).click();
    await page.getByRole('dialog', { name: 'Навигация' }).waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('button', { name: 'Открыть навигацию' }).evaluate(element => element === document.activeElement), true);
    assert.notEqual(await page.evaluate(() => document.body.style.overflow), 'hidden');
    checks.push('mobile drawer Escape/focus/scroll restoration');
    await page.setViewportSize({ width: 1280, height: 900 });
    return checks;
}
