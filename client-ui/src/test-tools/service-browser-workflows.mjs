async function syntheticPdf(name) {
    const document = new PDFDocument();
    const chunks = [];
    const done = new Promise((resolve, reject) => { document.on('data', chunk => chunks.push(chunk)); document.on('end', resolve); document.on('error', reject); });
    document.text('FE-1C SYNTHETIC TEST DOCUMENT. NOT FOR PAYMENT.');
    document.end(); await done;
    return { name, mimeType: 'application/pdf', buffer: Buffer.concat(chunks) };
}
