        const foreign = await login('foreign', `${queue}/${fixture.main.id}`);
        await foreign.getByRole('heading', { name: 'Заявка недоступна', exact: true }).waitFor();
        const sales = await login('sales', `${queue}/${fixture.main.id}`);
